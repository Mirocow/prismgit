const TABLE: Record<MenuLocale, Dict> = { en, ru, zh, de };

/** Active menu locale (set via IPC from the renderer / OS default at boot). */
let activeLocale: MenuLocale = 'en';

export function normalizeMenuLocale(raw: string | undefined | null): MenuLocale {
  const l = (raw || '').toLowerCase();
  if (l.startsWith('ru')) return 'ru';
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('de')) return 'de';
  return 'en';
}

/** Set the menu language (called on boot + from the renderer). */
export function setMenuLocale(locale: string): void {
  activeLocale = normalizeMenuLocale(locale);
}

/** Translate a menu string; falls back to English, then to the key itself. */
export function menuT(key: string): string {
  return TABLE[activeLocale]?.[key] ?? en[key] ?? key;
}
